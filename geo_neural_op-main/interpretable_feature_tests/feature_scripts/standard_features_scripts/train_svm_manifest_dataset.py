"""
train_svm_manifest_dataset.py
-----------------------------
Train and test an SVM on a Gaussian point-cloud dataset with a manifest.csv.

This is intended for datasets generated by:
    gaussian_dataset_creation/generate_gaussian_svm_datasets.py
"""

from __future__ import annotations

import argparse
import csv
import pickle
import sys
from pathlib import Path

import numpy as np
import torch
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
from sklearn.model_selection import GridSearchCV
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC


SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR.parents[1]))

from path_config import roots_for

ROOTS = roots_for(__file__)
REPO_ROOT = ROOTS["REPO_ROOT"]
TEST_ROOT = ROOTS["TEST_ROOT"]
DEFAULT_DATASET_DIR = ROOTS["OUTPUT_ROOT"] / "gaussian" / "datasets" / "modelnet10_smooth_shapes"

sys.path.insert(0, str(SCRIPT_DIR))
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(ROOTS["FEATURE_SCRIPTS_ROOT"]))
sys.path.insert(0, str(ROOTS["GAUSSIAN_SCRIPTS_ROOT"]))

from curvature import estimate_curvatures
from features import extract_features


INDICATOR_BINS = 4
VOXEL_BINS = 3
N_FOURIER = 64


def read_manifest(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    if not rows:
        raise ValueError(f"Manifest is empty: {path}")
    return rows


def load_points(csv_path: Path) -> np.ndarray:
    points = np.loadtxt(csv_path, delimiter=",", skiprows=1)
    points = np.asarray(points, dtype=np.float32)
    if points.ndim == 1:
        points = points.reshape(1, -1)
    return points[:, :3]


def process_points(points: np.ndarray, device: torch.device) -> np.ndarray:
    xyz_t, curvatures = estimate_curvatures(points, device)
    curvature_feats = extract_features(
        xyz_t,
        curvatures,
        indicator_bins=INDICATOR_BINS,
        voxel_bins=VOXEL_BINS,
        n_fourier=N_FOURIER,
    )["combined"]

    density_feats = extract_features(
        xyz_t,
        {"density": torch.ones(xyz_t.shape[0], device=xyz_t.device)},
        indicator_bins=INDICATOR_BINS,
        voxel_bins=VOXEL_BINS,
        n_fourier=N_FOURIER,
    )["combined"]
    return torch.cat([curvature_feats, density_feats]).detach().cpu().numpy()


def resolve_csv_path(dataset_dir: Path, row: dict[str, str]) -> Path:
    raw = row.get("csv_path")
    if not raw:
        raise ValueError(f"Manifest row has no csv_path: {row}")
    csv_path = Path(raw)
    if csv_path.exists():
        return csv_path
    matches = sorted(dataset_dir.rglob(csv_path.name))
    if matches:
        return matches[0]
    fallback = dataset_dir / csv_path.name
    if fallback.exists():
        return fallback
    raise FileNotFoundError(f"Could not resolve CSV path {raw!r} relative to {dataset_dir}")


def cache_is_fresh(cache_path: Path, manifest_path: Path, rows: list[dict[str, str]], dataset_dir: Path) -> bool:
    if not cache_path.exists():
        return False
    cache_mtime = cache_path.stat().st_mtime
    if manifest_path.stat().st_mtime > cache_mtime:
        return False
    return all(resolve_csv_path(dataset_dir, row).stat().st_mtime <= cache_mtime for row in rows)


def build_features(
    rows: list[dict[str, str]],
    dataset_dir: Path,
    classes: list[str],
    device: torch.device,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    class_to_idx = {name: idx for idx, name in enumerate(classes)}
    X_train, y_train, X_test, y_test = [], [], [], []

    for row in rows:
        split = row["split"]
        class_name = row["class_name"]
        csv_path = resolve_csv_path(dataset_dir, row)
        print(f"  [{split}] {class_name:8s} {csv_path.name}", flush=True)
        feature = process_points(load_points(csv_path), device)
        if split == "train":
            X_train.append(feature)
            y_train.append(class_to_idx[class_name])
        elif split == "test":
            X_test.append(feature)
            y_test.append(class_to_idx[class_name])
        else:
            raise ValueError(f"Unknown split {split!r} in {csv_path}")

    return np.vstack(X_train), np.array(y_train), np.vstack(X_test), np.array(y_test)


def train_and_eval(
    X_train: np.ndarray,
    y_train: np.ndarray,
    X_test: np.ndarray,
    y_test: np.ndarray,
    classes: list[str],
) -> tuple[StandardScaler, SVC, dict, float, float, str, np.ndarray]:
    scaler = StandardScaler()
    X_train_s = scaler.fit_transform(X_train)
    X_test_s = scaler.transform(X_test)
    cv = min(5, int(np.bincount(y_train).min()))
    param_grid = [
        {"kernel": ["linear"], "C": [0.1, 1.0, 10.0, 100.0]},
        {"kernel": ["rbf"], "C": [0.1, 1.0, 10.0, 100.0], "gamma": ["scale", "auto", 1e-3, 1e-2]},
        {"kernel": ["poly"], "C": [0.1, 1.0, 10.0], "degree": [2, 3], "gamma": ["scale", "auto"]},
    ]
    grid = GridSearchCV(SVC(decision_function_shape="ovr", random_state=0), param_grid, cv=cv, scoring="accuracy")
    grid.fit(X_train_s, y_train)
    clf = grid.best_estimator_
    y_pred = clf.predict(X_test_s)
    report = classification_report(y_test, y_pred, target_names=classes, zero_division=0)
    cm = confusion_matrix(y_test, y_pred)
    return scaler, clf, grid.best_params_, float(grid.best_score_), float(accuracy_score(y_test, y_pred)), report, cm


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Train an SVM from a generated Gaussian dataset manifest.")
    parser.add_argument("--dataset-dir", type=Path, default=DEFAULT_DATASET_DIR)
    parser.add_argument("--device", default="cuda" if torch.cuda.is_available() else "cpu")
    parser.add_argument("--recompute", action="store_true")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    manifest_path = args.dataset_dir / "manifest.csv"
    output_dir = args.dataset_dir / "svm_outputs"
    output_dir.mkdir(parents=True, exist_ok=True)
    cache_path = output_dir / "features.npz"

    rows = read_manifest(manifest_path)
    classes = sorted({row["class_name"] for row in rows})
    device = torch.device(args.device)
    print(f"Dataset: {args.dataset_dir}")
    print(f"Device : {device}")
    print(f"Classes: {classes}")

    if not args.recompute and cache_is_fresh(cache_path, manifest_path, rows, args.dataset_dir):
        cached = np.load(cache_path, allow_pickle=True)
        X_train = cached["X_train"]
        y_train = cached["y_train"]
        X_test = cached["X_test"]
        y_test = cached["y_test"]
        print(f"Loaded cached features: {cache_path}")
    else:
        X_train, y_train, X_test, y_test = build_features(rows, args.dataset_dir, classes, device)
        np.savez(
            cache_path,
            X_train=X_train,
            y_train=y_train,
            X_test=X_test,
            y_test=y_test,
            classes=np.array(classes),
        )
        print(f"Saved features: {cache_path}")

    scaler, clf, best_params, best_cv, test_acc, report, cm = train_and_eval(
        X_train,
        y_train,
        X_test,
        y_test,
        classes,
    )

    results_path = output_dir / "results.txt"
    results_path.write_text(
        f"Classes: {classes}\n"
        f"Train shape: {X_train.shape}\n"
        f"Test shape: {X_test.shape}\n"
        f"Best params: {best_params}\n"
        f"Best CV acc: {best_cv:.3f}\n"
        f"Test acc: {test_acc:.3f}\n\n"
        "=== Classification Report ===\n"
        + report
        + "\nConfusion Matrix:\n"
        + str(cm)
        + "\n",
        encoding="utf-8",
    )
    with (output_dir / "model.pkl").open("wb") as handle:
        pickle.dump(
            {
                "svm": clf,
                "scaler": scaler,
                "classes": classes,
                "best_params": best_params,
                "best_cv_accuracy": best_cv,
                "test_accuracy": test_acc,
            },
            handle,
        )

    print(f"Train: {X_train.shape}  Test: {X_test.shape}")
    print(f"Best params: {best_params}")
    print(f"Best CV acc: {best_cv:.3f}")
    print(f"Test acc   : {test_acc:.3f}")
    print(f"Saved results: {results_path}")


if __name__ == "__main__":
    main()
